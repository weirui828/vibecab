import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import { resolve, relative } from "node:path";
import { compile } from "json-schema-to-typescript";
const root = resolve("contract/schemas");
const files = (await readdir(root, { recursive: true })).filter((f) => f.endsWith(".json")).sort();
const records = await Promise.all(
  files.map(async (file) => ({
    path: file.replaceAll("\\", "/"),
    schema: JSON.parse(await readFile(resolve(root, file), "utf8")),
  })),
);
const schemas = new Map(records.map(({ path, schema }) => [schema.$id, resolve(root, path)]));
const exports = [];
for (const file of files) {
  const schema = JSON.parse(await readFile(resolve(root, file), "utf8"));
  const output = await compile(schema, schema.title, {
    bannerComment: "/* Generated by pnpm gen. Do not edit. */",
    additionalProperties: false,
    $refOptions: {
      resolve: {
        local: {
          order: 1,
          canRead: (f) => schemas.has(f.url),
          read: async (f) => readFile(schemas.get(f.url), "utf8"),
        },
      },
    },
  });
  const target = resolve("contract/generated", file.replace(/\.json$/, ".ts"));
  await mkdir(resolve(target, ".."), { recursive: true });
  await writeFile(target, output);
  exports.push(
    `export type { ${schema.title[0].toUpperCase() + schema.title.slice(1)} } from './${relative(resolve("contract/generated"), target).replace(/\.ts$/, ".js")}';`,
  );
}
await writeFile("contract/generated/index.ts", exports.join("\n") + "\n");
const schemasById = Object.fromEntries(records.map(({ schema }) => [schema.$id, schema]));
const schemasByPath = Object.fromEntries(records.map(({ path, schema }) => [path, schema.$id]));
await writeFile(
  "contract/generated/schemas.ts",
  `/* Generated by pnpm gen. Do not edit. */\nimport type { AnySchema } from "ajv";\n\nexport const schemasById: Record<string, AnySchema> = ${JSON.stringify(schemasById, null, 2)};\n\nexport const schemasByPath: Record<string, string> = ${JSON.stringify(schemasByPath, null, 2)};\n`,
);
